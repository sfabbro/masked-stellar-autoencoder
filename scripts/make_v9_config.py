"""Write the v9 fine-tune config: v8 without the fixed binary pool, plus
wide-binary self-consistency.

usage: make_v9_config.py [--ratio R]

The full-data v8 ablations (2026-11-20) showed that the fixed reference pool
(cool companions labelled with v7's [Fe/H] of their primary) caused v8's
bulk [Fe/H] regression (NMAD > -1: 0.142 -> 0.185; 0.149 without the pool)
and its -0.05 dex scale shift, because the companions stayed pinned to v7's
scale while the model's moved. v9 keeps v8's c03 sources and [Fe/H]-balanced
sampling and replaces the pool by ``reference_pool.mode: pairs``: each cool
companion (< 5000 K) is tied to the model's own current prediction for its
FGK primary (no offset, no fixed teacher values).
"""

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_v7_configs import ROOT  # noqa: E402

HERE = Path(__file__).resolve().parent.parent
BASE = HERE / "configs/finetune-multisurvey-20261119-v8-nopool.yaml"
V9 = HERE / "configs/finetune-multisurvey-20261120-v9.yaml"
RUN = ROOT + "multisurvey_finetune_20261120_v9/"
POOL = ROOT + "binary_pool_20261120_pairs/pool.npz"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--ratio", type=float, default=0.1)
    a = p.parse_args()
    c = yaml.safe_load(BASE.read_text())
    ms = c["multisurvey"]
    assert "reference_pool" not in ms and ms.get("balance")
    ms["reference_pool"] = {"path": POOL, "ratio": a.ratio, "mode": "pairs"}
    c["saving"]["model_str"] = RUN + "finetune.pth"
    c["saving"]["log_file"] = RUN + "finetune.log"
    V9.write_text(
        "# Generated by scripts/make_v9_config.py from the v8-nopool config.\n"
        "# v9 = v8 (c03 sources + balanced sampling, single Student-t head),\n"
        "# cool wide-binary companions tied to the model's own primary [Fe/H].\n"
        f"# command: make_v9_config.py {' '.join(sys.argv[1:])}\n"
        + yaml.safe_dump(c, sort_keys=False)
    )
    print("wrote", V9.name)


if __name__ == "__main__":
    main()
