"""Write the v10 fine-tune config: v8 without the pool, [Fe/H] core as identity.

usage: make_v10_config.py

S1 diagnostics (2026-11-21) found that the high-resolution [Fe/H] core
catalogues, mapped with free offsets summing to zero over the core, did not
fix the scale at low metallicity: every metal-poor-only literature catalogue
took a +0.1 to +0.33 dex offset (Yong 2013 +0.33, SMSS +0.27, Li 2022 +0.29,
JINAbase +0.25), absorbing the head's pull toward solar and lifting the common
scale by ~0.25 dex below [Fe/H] = -2.5 (Gaia-ESO, PASTEL, Bensby: ~0). A 1-D
likelihood head trained on the raw references was unbiased (+0.03 / -0.01 /
-0.03 below -3 / -3..-2.5 / -2.5..-2); the same head on the mapped references
reproduced the bias (+0.33 / +0.19 / +0.10). v10 keeps v8-without-pool (c03
sources, balanced sampling, single Student-t head) and puts the core
references on the identity map (``fe_h_core_mode: identity``), like the IRFM
Teff and seismic log g anchors.
"""

import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_v7_configs import ROOT  # noqa: E402

HERE = Path(__file__).resolve().parent.parent
BASE = HERE / "configs/finetune-multisurvey-20261119-v8-nopool.yaml"
V10 = HERE / "configs/finetune-multisurvey-20261121-v10.yaml"
RUN = ROOT + "multisurvey_finetune_20261121_v10/"


def main():
    c = yaml.safe_load(BASE.read_text())
    ms = c["multisurvey"]
    assert "reference_pool" not in ms and ms.get("balance")
    ms["fe_h_core_mode"] = "identity"
    c["saving"]["model_str"] = RUN + "finetune.pth"
    c["saving"]["log_file"] = RUN + "finetune.log"
    V10.write_text(
        "# Generated by scripts/make_v10_config.py from the v8-nopool config.\n"
        "# v10 = v8 without the pool + [Fe/H] core references on the identity map.\n"
        + yaml.safe_dump(c, sort_keys=False)
    )
    print("wrote", V10.name)


if __name__ == "__main__":
    main()
