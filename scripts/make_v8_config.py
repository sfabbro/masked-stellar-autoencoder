"""Write the v8 fine-tune config from v7 and the ablation verdicts.

usage: make_v8_config.py [--components K] [--gaussian] [--balance]
                         [--pool-ratio R] [--no-pool]

v8 = v7 (full table, 12 epochs) +
* the c03 source set: The Payne, ApogeeNet and astroNN dropped (redundant
  pipelines on APOGEE spectra), literature values deduplicated (original
  papers before compilations);
* wide-binary companions cooler than 5000 K inheriting their FGK primary's
  [Fe/H] (reference pool; d03 removed the cool-dwarf offset on held-out
  pairs, +0.45 -> 0.00 dex at 3000-3700 K; cool companions only and a lower
  ratio, since the full pool of mostly near-solar stars cost metal-poor
  accuracy);
* optional: a K-component mixture head (``--components``; Student-t unless
  ``--gaussian``) and [Fe/H]-balanced sampling (``--balance``, d02).
"""

import argparse
import copy
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_v7_configs import C03, ROOT, _groups_plus_literature  # noqa: E402

HERE = Path(__file__).resolve().parent.parent
V7 = HERE / "configs/finetune-multisurvey-20261118-v7.yaml"
V6 = HERE / "configs/finetune-multisurvey-20261118-v6.yaml"
V8 = HERE / "configs/finetune-multisurvey-20261119-v8.yaml"
RUN = ROOT + "multisurvey_finetune_20261119_v8/"
POOL = ROOT + "binary_pool_20261119_cool/pool.npz"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--components", type=int, default=1)
    p.add_argument("--gaussian", action="store_true")
    p.add_argument("--diagonal", action="store_true")
    p.add_argument("--balance", action="store_true")
    p.add_argument("--pool-ratio", type=float, default=0.1)
    p.add_argument("--no-pool", action="store_true")
    a = p.parse_args()
    v6 = yaml.safe_load(V6.read_text())
    c = yaml.safe_load(V7.read_text())
    ms = c["multisurvey"]
    ms.update(copy.deepcopy(C03))
    ms["spectra_groups"] = _groups_plus_literature(v6)
    if not a.no_pool:
        ms["reference_pool"] = {"path": POOL, "ratio": a.pool_ratio}
    if a.components > 1:
        ms["n_components"] = a.components
        if a.diagonal:
            ms["full_covariance"] = False
    if a.gaussian:
        ms["nu"] = 1000.0
    if a.balance:
        ms["balance"] = {"power": 0.5, "cap": 10.0}
    c["saving"]["model_str"] = RUN + "finetune.pth"
    c["saving"]["log_file"] = RUN + "finetune.log"
    head = (
        f"{a.components}-component {'Gaussian' if a.gaussian else 'Student-t'}"
        f"{' diagonal' if a.diagonal else ''} head"
    )
    V8.write_text(
        "# Generated by scripts/make_v8_config.py from the v7 config.\n"
        f"# v8 = v7 + c03 sources + {'no pool' if a.no_pool else 'cool binary pool'}"
        f" + {head}{' + balanced sampling' if a.balance else ''}.\n"
        f"# command: make_v8_config.py {' '.join(sys.argv[1:])}\n"
        + yaml.safe_dump(c, sort_keys=False)
    )
    print("wrote", V8.name, head)


if __name__ == "__main__":
    main()
